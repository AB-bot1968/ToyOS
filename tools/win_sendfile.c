/* ========================================================================== */
/* win_sendfile.c                                                             */
/* Утилита передаёт содержимое указанного файла в QEMU по TCP через Winsock.  */
/* ========================================================================== */

#define WIN32_LEAN_AND_MEAN /* Не подключаем устаревший Winsock 1.x из Windows.h. */
#include <winsock2.h>       /* Подключаем API Windows Sockets 2. */
#include <ws2tcpip.h>      /* Подключаем определения TCP/IP. */
#include <stdio.h>         /* Подключаем функции стандартного ввода-вывода. */
#include <stdlib.h>        /* Подключаем EXIT_SUCCESS и EXIT_FAILURE. */
#include <string.h>        /* Подключаем memset для очистки структуры адреса. */

#define SERVER_IP "127.0.0.1" /* Задаём адрес QEMU в локальном компьютере. */
#define SERVER_PORT 5555      /* Задаём TCP-порт, который слушает QEMU. */
#define BUFFER_SIZE 4096      /* Задаём размер буфера чтения файла. */

/* Функция печатает сообщение об ошибке Winsock и возвращает код ошибки. */
static int print_wsa_error(const char *where) /* Выполняем операцию, указанную в этой строке. */
{ /* Открываем блок кода. */
    /* Получаем последний код ошибки Winsock. */
    int error = WSAGetLastError(); /* Выполняем операцию, указанную в этой строке. */
    /* Печатаем место возникновения ошибки и её числовой код. */
    fprintf(stderr, "%s: WSA error %d\n", where, error); /* Выполняем операцию, указанную в этой строке. */
    /* Возвращаем ненулевой код для вызывающей функции. */
    return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
} /* Закрываем блок кода. */

/* Главная функция получает имя передаваемого файла из командной строки. */
int main(int argc, char **argv) /* Выполняем операцию, указанную в этой строке. */
{ /* Открываем блок кода. */
    /* Объявляем структуру состояния Winsock. */
    WSADATA wsa_data; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем TCP-сокет, изначально недействительный. */
    SOCKET sock = INVALID_SOCKET; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем дескриптор исходного файла. */
    FILE *file = NULL; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем буфер для чтения файла частями. */
    unsigned char buffer[BUFFER_SIZE]; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем количество прочитанных байт. */
    size_t bytes_read; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем общее количество переданных байт. */
    unsigned long long total_sent = 0; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем структуру адреса TCP-сервера. */
    struct sockaddr_in server; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем результат работы Winsock. */
    int result; /* Выполняем операцию, указанную в этой строке. */
    /* Объявляем индекс уже переданных байт текущего блока. */
    size_t offset; /* Выполняем операцию, указанную в этой строке. */

    /* Проверяем, что пользователь передал ровно один параметр. */
    if (argc != 2) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Печатаем правильный формат запуска программы. */
        fprintf(stderr, "Usage: %s <file>\n", argv[0]); /* Выполняем операцию, указанную в этой строке. */
        /* Возвращаем код ошибки параметров. */
        return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
    } /* Закрываем блок кода. */

    /* Открываем передаваемый файл в бинарном режиме. */
    file = fopen(argv[1], "rb"); /* Выполняем операцию, указанную в этой строке. */
    /* Проверяем успешность открытия файла. */
    if (file == NULL) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Печатаем имя файла, который не удалось открыть. */
        fprintf(stderr, "Cannot open file: %s\n", argv[1]); /* Выполняем операцию, указанную в этой строке. */
        /* Завершаем программу с ошибкой. */
        return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
    } /* Закрываем блок кода. */

    /* Запускаем Windows Sockets версии 2.2. */
    result = WSAStartup(MAKEWORD(2, 2), &wsa_data); /* Выполняем операцию, указанную в этой строке. */
    /* Проверяем результат запуска Winsock. */
    if (result != 0) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Печатаем код ошибки и закрываем исходный файл. */
        fprintf(stderr, "WSAStartup failed: %d\n", result); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем файл перед завершением программы. */
        fclose(file); /* Выполняем операцию, указанную в этой строке. */
        /* Возвращаем код ошибки. */
        return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
    } /* Закрываем блок кода. */

    /* Создаём потоковый TCP-сокет IPv4. */
    sock = socket(AF_INET, SOCK_STREAM, IPPROTO_TCP); /* Выполняем операцию, указанную в этой строке. */
    /* Проверяем успешность создания сокета. */
    if (sock == INVALID_SOCKET) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Печатаем подробную ошибку Winsock. */
        print_wsa_error("socket"); /* Выполняем операцию, указанную в этой строке. */
        /* Освобождаем ресурсы Winsock. */
        WSACleanup(); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем исходный файл. */
        fclose(file); /* Выполняем операцию, указанную в этой строке. */
        /* Возвращаем код ошибки. */
        return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
    } /* Закрываем блок кода. */

    /* Обнуляем структуру адреса перед заполнением. */
    memset(&server, 0, sizeof(server)); /* Выполняем операцию, указанную в этой строке. */
    /* Указываем IPv4 как семейство адресов. */
    server.sin_family = AF_INET; /* Выполняем операцию, указанную в этой строке. */
    /* Преобразуем текстовый адрес 127.0.0.1 в IPv4. */
    server.sin_addr.s_addr = inet_addr(SERVER_IP); /* Выполняем операцию, указанную в этой строке. */
    /* Преобразуем номер порта в сетевой порядок байт. */
    server.sin_port = htons(SERVER_PORT); /* Выполняем операцию, указанную в этой строке. */

    /* Подключаем TCP-сокет к QEMU. */
    result = connect(sock, (const struct sockaddr *)&server, sizeof(server)); /* Выполняем операцию, указанную в этой строке. */
    /* Проверяем результат подключения. */
    if (result == SOCKET_ERROR) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Печатаем подробную ошибку подключения. */
        print_wsa_error("connect"); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем сокет. */
        closesocket(sock); /* Выполняем операцию, указанную в этой строке. */
        /* Освобождаем Winsock. */
        WSACleanup(); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем исходный файл. */
        fclose(file); /* Выполняем операцию, указанную в этой строке. */
        /* Возвращаем код ошибки. */
        return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
    } /* Закрываем блок кода. */

    /* Сообщаем пользователю об успешном подключении. */
    printf("Connected to QEMU %s:%d\n", SERVER_IP, SERVER_PORT); /* Выполняем операцию, указанную в этой строке. */
    /* Печатаем имя передаваемого файла. */
    printf("Sending: %s\n", argv[1]); /* Выполняем операцию, указанную в этой строке. */

    /* Читаем файл блоками до достижения конца файла. */
    while ((bytes_read = fread(buffer, 1, sizeof(buffer), file)) != 0) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Сбрасываем позицию внутри текущего блока. */
        offset = 0; /* Выполняем операцию, указанную в этой строке. */
        /* Повторяем отправку, пока весь блок не будет передан. */
        while (offset < bytes_read) /* Выполняем операцию, указанную в этой строке. */
        { /* Открываем блок кода. */
            /* Отправляем оставшуюся часть текущего блока через TCP. */
            result = send(sock, (const char *)buffer + offset, /* Выполняем операцию, указанную в этой строке. */
                          (int)(bytes_read - offset), 0); /* Выполняем операцию, указанную в этой строке. */
            /* Проверяем результат функции send. */
            if (result == SOCKET_ERROR) /* Выполняем операцию, указанную в этой строке. */
            { /* Открываем блок кода. */
                /* Печатаем подробную ошибку передачи. */
                print_wsa_error("send"); /* Выполняем операцию, указанную в этой строке. */
                /* Закрываем сокет. */
                closesocket(sock); /* Выполняем операцию, указанную в этой строке. */
                /* Освобождаем Winsock. */
                WSACleanup(); /* Выполняем операцию, указанную в этой строке. */
                /* Закрываем исходный файл. */
                fclose(file); /* Выполняем операцию, указанную в этой строке. */
                /* Возвращаем код ошибки. */
                return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
            } /* Закрываем блок кода. */

            /* Проверяем защиту от неожиданного нулевого результата. */
            if (result == 0) /* Выполняем операцию, указанную в этой строке. */
            { /* Открываем блок кода. */
                /* Сообщаем, что соединение не приняло данные. */
                fprintf(stderr, "send returned zero bytes\n"); /* Выполняем операцию, указанную в этой строке. */
                /* Закрываем сокет. */
                closesocket(sock); /* Выполняем операцию, указанную в этой строке. */
                /* Освобождаем Winsock. */
                WSACleanup(); /* Выполняем операцию, указанную в этой строке. */
                /* Закрываем исходный файл. */
                fclose(file); /* Выполняем операцию, указанную в этой строке. */
                /* Возвращаем код ошибки. */
                return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
            } /* Закрываем блок кода. */

            /* Продвигаем позицию на фактически переданное количество байт. */
            offset += (size_t)result; /* Выполняем операцию, указанную в этой строке. */
            /* Увеличиваем общий счётчик переданных байт. */
            total_sent += (unsigned long long)result; /* Выполняем операцию, указанную в этой строке. */
        } /* Закрываем блок кода. */
    } /* Закрываем блок кода. */

    /* Проверяем ошибку чтения файла после завершения цикла. */
    if (ferror(file)) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Сообщаем об ошибке чтения исходного файла. */
        fprintf(stderr, "File read error: %s\n", argv[1]); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем сокет. */
        closesocket(sock); /* Выполняем операцию, указанную в этой строке. */
        /* Освобождаем Winsock. */
        WSACleanup(); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем исходный файл. */
        fclose(file); /* Выполняем операцию, указанную в этой строке. */
        /* Возвращаем код ошибки. */
        return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
    } /* Закрываем блок кода. */

    /* Закрываем направление отправки TCP-соединения. */
    result = shutdown(sock, SD_SEND); /* Выполняем операцию, указанную в этой строке. */
    /* Проверяем результат завершения отправки. */
    if (result == SOCKET_ERROR) /* Выполняем операцию, указанную в этой строке. */
    { /* Открываем блок кода. */
        /* Печатаем ошибку shutdown, не считая файл потерянным. */
        print_wsa_error("shutdown"); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем сокет. */
        closesocket(sock); /* Выполняем операцию, указанную в этой строке. */
        /* Освобождаем Winsock. */
        WSACleanup(); /* Выполняем операцию, указанную в этой строке. */
        /* Закрываем исходный файл. */
        fclose(file); /* Выполняем операцию, указанную в этой строке. */
        /* Возвращаем код ошибки. */
        return EXIT_FAILURE; /* Выполняем операцию, указанную в этой строке. */
    } /* Закрываем блок кода. */

    /* Печатаем итоговое количество переданных байт. */
    printf("Sent: %llu bytes\n", total_sent); /* Выполняем операцию, указанную в этой строке. */
    /* Закрываем TCP-сокет. */
    closesocket(sock); /* Выполняем операцию, указанную в этой строке. */
    /* Освобождаем ресурсы Winsock. */
    WSACleanup(); /* Выполняем операцию, указанную в этой строке. */
    /* Закрываем исходный файл. */
    fclose(file); /* Выполняем операцию, указанную в этой строке. */
    /* Сообщаем об успешном завершении. */
    return EXIT_SUCCESS; /* Выполняем операцию, указанную в этой строке. */
} /* Закрываем блок кода. */
